function K({ children }: { children: ReactNode }) {
  return <kbd className="help-kbd">{children}</kbd>
}

/** 키 조합 한 벌을 <kbd>+<kbd> 형태로. */
function Combo({ keys }: { keys: string[] }) {
  return (
    <>
      {keys.map((key, i) => (
        <span key={key}>
          {i > 0 && '+'}
          <K>{key}</K>
        </span>
      ))}
    </>
  )
}

